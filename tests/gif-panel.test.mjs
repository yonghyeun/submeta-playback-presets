async function settle(){for(let i=0;i<20;i++)await new Promise(resolve=>setImmediate(resolve));}
async function waitForResult(h){
  const deadline=Date.now()+5000;
  while(!(h.state.busy==='idle'&&h.state.previewURL)&&Date.now()<deadline)await new Promise(resolve=>setTimeout(resolve,10));
  assert.equal(h.state.busy,'idle');assert.ok(h.state.previewURL,'GIF generation should finish');
}
