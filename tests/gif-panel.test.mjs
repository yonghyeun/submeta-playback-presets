test('GIF opening selects the current playback position and next five seconds every time',async()=>{
  const h=setup();await settle();
  h.video.currentTime=72.34;await h.message({type:'gif:ui-open'});
  assert.equal(h.state.start,'1:12.3');assert.equal(h.state.end,'1:17.3');
  h.actions.changeTime('start','0:10');h.actions.changeTime('end','0:15');
  await h.message({type:'gif:ui-close'});h.video.currentTime=100;
  await h.message({type:'gif:ui-open'});
  assert.equal(h.state.start,'1:40');assert.equal(h.state.end,'1:45');
  h.video.currentTime=283;await h.message({type:'gif:ui-open'});
  assert.equal(h.state.start,'4:43');assert.equal(h.state.end,'4:45');assert.equal(h.state.timeError,'');
  h.video.currentTime=284.5;await h.message({type:'gif:ui-open'});
  assert.equal(h.state.start,'4:44.5');assert.equal(h.state.end,'4:45');assert.ok(h.state.timeError);
});
test('GIF reopening resets the range while cancelled generation is still settling',async()=>{
  let finishCapture;
  const h=setup({capture:()=>new Promise(resolve=>{finishCapture=resolve;})});
  await settle();h.actions.generate();await settle();
  assert.equal(h.state.busy,'generating');
  await h.message({type:'gif:ui-close'});h.video.currentTime=80;
  await h.message({type:'gif:ui-open'});
  assert.equal(h.state.start,'1:20');assert.equal(h.state.end,'1:25');
  finishCapture({error:'cancelled',report:{restoration:'restored'}});await settle();
  assert.equal(h.state.busy,'idle');assert.equal(h.state.start,'1:20');assert.equal(h.state.end,'1:25');
});
test('GIF controller retains generated bytes across save failure and retry',async()=>{
  const h=setup();await settle();h.actions.generate();await waitForResult(h);
  assert.equal(h.state.busy,'idle');assert.equal(h.state.previewURL,'blob:fixture-preview');
  assert.equal(h.encoderDisposed,1);assert.equal(h.saves[0].options.destination,'clipboard');
  assert.ok(h.updates.some(state=>state.busy==='copying'));
  const result=h.saves[0].result;
  h.saveResponse={error:'file-no-space'};h.actions.save('remembered-folder');await settle();
  assert.equal(h.state.tone,'error');assert.equal(h.state.previewURL,result.url);
  h.saveResponse={status:'complete'};h.actions.save('browser');await settle();
  assert.equal(h.saves.at(-1).result,result);assert.equal(h.state.tone,'success');
  assert.equal(h.saves.at(-1).options.destination,'browser');
  h.events.pagehide();assert.deepEqual(h.revoked,[result.url]);
});
test('GIF cancellation aborts capture, retains times and disposes encoder',async()=>{
  let aborted=false;
  const h=setup({capture:({controller})=>new Promise(resolve=>controller.signal.addEventListener('abort',()=>{aborted=true;resolve({error:'cancelled',report:{restoration:'restored'}});} ))});
  await settle();h.actions.changeTime('start','0:40');h.actions.changeTime('end','0:45');h.actions.generate();await settle();
  assert.equal(h.state.busy,'generating');h.actions.cancel();await settle();
  assert.equal(aborted,true);assert.equal(h.state.busy,'idle');assert.equal(h.state.start,'0:40');assert.equal(h.state.end,'0:45');assert.match(h.state.status,/취소/);assert.equal(h.encoderDisposed,1);assert.equal(h.saves.length,0);
});
